def post_batch(batch):
    records = [{"fields": r} for r in batch]
    body    = json.dumps({"records": records}).encode()
    req     = urllib.request.Request(URL, data=body, method="POST",
              headers={"Authorization": f"Bearer {API_KEY}",
                       "Content-Type": "application/json"})
    with urllib.request.urlopen(req) as r:
        return json.loads(r.read())


def main():
    batches = [RECORDS[i:i+10] for i in range(0, len(RECORDS), 10)]
    total   = 0
    for i, batch in enumerate(batches):
        resp = post_batch(batch)
        n    = len(resp.get("records", []))
        total += n
        print(f"Batch {i+1}/{len(batches)}: created {n} records")
        if i < len(batches) - 1:
            time.sleep(0.3)   # stay well inside rate limit
    print(f"\nDone — {total} QA_EVAL records created.")


if __name__ == '__main__':
    main()
